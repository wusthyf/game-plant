def shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr(); shd = OxmlElement('w:shd'); shd.set(qn('w:fill'), fill); tcPr.append(shd)

def margins(cell, top=100, start=120, bottom=100, end=120):
    tc = cell._tc; tcPr = tc.get_or_add_tcPr(); mar = tcPr.first_child_found_in('w:tcMar')
    if mar is None: mar = OxmlElement('w:tcMar'); tcPr.append(mar)
    for side, val in [('top',top),('start',start),('bottom',bottom),('end',end)]:
        node = mar.find(qn('w:' + side))
        if node is None: node = OxmlElement('w:' + side); mar.append(node)
        node.set(qn('w:w'), str(val)); node.set(qn('w:type'), 'dxa')

def set_repeat_table_header(row):
    trPr = row._tr.get_or_add_trPr(); tblHeader = OxmlElement('w:tblHeader'); tblHeader.set(qn('w:val'), 'true'); trPr.append(tblHeader)

def prevent_row_split(row):
    trPr = row._tr.get_or_add_trPr()
    no_split = OxmlElement('w:cantSplit')
    trPr.append(no_split)

def p(text='', style=None, bold_lead=None):
    para = doc.add_paragraph(style=style)
    if bold_lead and text.startswith(bold_lead):
        r = para.add_run(bold_lead); set_font(r, bold=True)
        r = para.add_run(text[len(bold_lead):]); set_font(r)
    else:
        r = para.add_run(text); set_font(r)
    return para

def title(text):
    para = doc.add_paragraph(style='Title'); para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = para.add_run(text); set_font(r, 24, True)

def h(text, level=1):
    para = doc.add_paragraph(style=f'Heading {level}')
    r = para.add_run(text); set_font(r, {1:16,2:12.5,3:11}[level], True)
    return para

def table(headers, rows, widths=None):
    tbl = doc.add_table(rows=1, cols=len(headers)); tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl.style = 'Table Grid'; tbl.autofit = False
    hdr = tbl.rows[0]; set_repeat_table_header(hdr); prevent_row_split(hdr)
    for i, val in enumerate(headers):
        cell = hdr.cells[i]; cell.text = ''; shade(cell, '2F5D50'); margins(cell)
        if widths: cell.width = Cm(widths[i])
        pp = cell.paragraphs[0]; pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        rr = pp.add_run(val); set_font(rr, 9.5, True, (255,255,255)); cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    for n, row in enumerate(rows):
        new_row = tbl.add_row(); prevent_row_split(new_row); cells = new_row.cells
        for i, val in enumerate(row):
            cell = cells[i]; cell.text = ''; margins(cell)
            if n % 2 == 1: shade(cell, 'EEF5F0')
            if widths: cell.width = Cm(widths[i])
            pp = cell.paragraphs[0]
            rr = pp.add_run(str(val)); set_font(rr, 9.2)
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return tbl

def bullets(items):
    for item in items:
        para = doc.add_paragraph(style='List Bullet')
        r = para.add_run(item); set_font(r)

